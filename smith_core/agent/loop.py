import time
from dataclasses import dataclass
from smith_core.models import SolutionOutput, StepMetrics
from smith_core.agent.extract import extract_code

# global variable for budget_left (visual preference)
MIN_OUTPUT_TOKEN = 200
OBSERVATION_MARGIN = 500
STEP_TIME_MARGIN_S = 5

# global variable for format_observation (visual preference)
MAX_OBS_CHARS = 2000

# global variable for run_agent (visual preference)
MAX_TOKENS_PER_TURN = 1024


@dataclass
class Limits:
    max_iterations: int = 10
    max_input_tokens: int = 6000
    max_output_tokens: int = 1500
    timeout_s: int = 120


def budget_left(steps, limits: Limits, start) -> bool:
    """
    Determine if there is enough budget left to continue processing steps.
    Args:
        steps (list): A list of step objects, where each step contains
            attributes such as `request_time_ms`, `output_tokens`,
            and `input_tokens`.
        limits (Limits): An object containing the following attributes:
            - `timeout_s` (float): The maximum allowed time in seconds.
            - `max_output_tokens` (int): The maximum number of output
                tokens allowed.
            - `max_input_tokens` (int): The maximum number of input
                tokens allowed.
        start (float): The starting time (monotonic) of the process.
    Returns:
        bool: True if there is enough budget left to continue, False otherwise.
    """

    elapsed = time.monotonic() - start
    if elapsed >= limits.timeout_s:
        return False
    if not steps:
        return True

    slowest_s = max(s.request_time_ms for s in steps) / 1000
    if elapsed + slowest_s + STEP_TIME_MARGIN_S >= limits.timeout_s:
        return False

    output_left = limits.max_output_tokens - sum(s.output_tokens
                                                 for s in steps)
    if output_left < MIN_OUTPUT_TOKEN:
        return False

    used_input = sum(s.input_tokens for s in steps)
    last = steps[-1]
    next_input = last.input_tokens + last.output_tokens + OBSERVATION_MARGIN

    return used_input + next_input <= limits.max_input_tokens


def format_observation(result, notice=""):
    """
    Formats the observation based on the provided result and optional notice.
    This function takes a result object and an optional notice string, then
    constructs a formatted string that includes notices, timeout information,
    and the result's output. If the output exceeds a predefined maximum
    character limit (MAX_OBS_CHARS), it truncates the output and indicates
    the truncation.
    Args:
        result: An object containing the following attributes:
            - notices (list of str): A list of notices to include
                in the output.
            - timed_out (bool): A flag indicating if the execution timed out.
            - output (str): The output string to format.
        notice (str, optional): An additional notice to prepend to the output.
            Defaults to an empty string.
    Returns:
        str: A formatted string containing the notice, notices, timeout
        information, and the processed output.
    """

    parts = []

    if notice:
        parts.append(notice)
    parts.extend(result.notices)
    if result.timed_out:
        parts.append("Execution timed out.")

    output = result.output.strip()
    if not output:
        output = "(no output)"
    elif len(output) > MAX_OBS_CHARS:
        half = MAX_OBS_CHARS // 2
        cut = len(output) - MAX_OBS_CHARS
        output = (output[:half]
                  + f"\n[... truncated {cut} chars ...]\n"
                  + output[-half:])
    parts.append(output)
    return "\n".join(parts)


def run_agent(task_id, benchmark, system_prompt, user_prompt, sandbox, llm,
              limits, fallback):
    """
    Executes an agent loop to solve a given task using an LLM
        (Large Language Model) and a sandbox environment.
    Args:
        task_id (str): Identifier for the task being executed.
        benchmark (str): Benchmark name or identifier for the task.
        system_prompt (str): Initial system prompt to guide the LLM.
        user_prompt (str): Initial user prompt to provide context
            or instructions.
        sandbox (Sandbox): Sandbox environment for executing code
            generated by the LLM.
        llm (LLM): Large Language Model instance used for generating responses.
        limits (Limits): Constraints on the execution, including
            max iterations and token limits.
        fallback (Callable[[], str]): Fallback function to provide a
            default solution in case of failure.
    Returns:
        SolutionOutput: An object containing the results of the agent's
            execution, including:
            - task_id (str): The task identifier.
            - benchmark (str): The benchmark name or identifier.
            - success (bool): Whether the task was successfully solved.
            - solution (str): The solution generated by the agent or the
                fallback solution.
            - iterations (int): Number of iterations performed in the loop.
            - total_requests (int): Total number of requests made to the LLM.
            - total_input_tokens (int): Total number of input tokens used.
            - total_output_tokens (int): Total number of output
                tokens generated.
            - total_time_seconds (float): Total time taken for execution
                in seconds.
            - steps (list[StepMetrics]): Detailed metrics for each step
                in the loop.
            - system_prompt (str): The initial system prompt used.
            - error (str or None): Error message if the task was not
                successfully solved.
    Raises:
        Exception: If an unexpected error occurs during the execution of
            the agent loop.
    """

    messages = [{"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}]
    steps: list[StepMetrics] = []
    start = time.monotonic()
    answer = None
    error = None
    for i in range(1, limits.max_iterations + 1):
        if not budget_left(steps, limits, start):
            error = "budget exhausted"
            break
        remaining_output_tokens = limits.max_output_tokens - sum(
            step.output_tokens for step in steps
        )
        try:
            resp = llm.chat(
                messages,
                max_tokens=min(remaining_output_tokens, MAX_TOKENS_PER_TURN),
                stop=["<end_code>"],
            )
        except Exception as exc:
            error = f"LLM call failed: {type(exc).__name__}: {exc}"
            break
        code, notice = extract_code(resp.text)
        sandbox_input, sandbox_output = "", ""
        if code is None:
            observation = notice
        else:
            result = sandbox.execute(code)
            observation = format_observation(result, notice)
            sandbox_input = code
            sandbox_output = result.output
            answer = result.final_answer
        steps.append(StepMetrics(
            step=i,
            input_tokens=resp.input_tokens,
            output_tokens=resp.output_tokens,
            request_time_ms=resp.request_time_ms,
            api_url=resp.api_url,
            model_name=resp.model_name,
            llm_output=resp.text,
            sandbox_input=sandbox_input,
            sandbox_output=sandbox_output,
            retries=resp.retries,
        ))
        if answer is not None:
            break
        messages.append({"role": "assistant", "content": resp.text})
        messages.append({"role": "user",
                        "content": "Observation:\n" + observation})
    else:
        error = "max iterations reached"

    success = answer is not None
    return SolutionOutput(
        task_id=str(task_id),
        benchmark=benchmark,
        success=success,
        solution=answer if success else fallback(),
        iterations=len(steps),
        total_requests=sum(1 + s.retries for s in steps),
        total_input_tokens=sum(s.input_tokens for s in steps),
        total_output_tokens=sum(s.output_tokens for s in steps),
        total_time_seconds=time.monotonic() - start,
        steps=steps,
        system_prompt=system_prompt,
        error=None if success else error,
    )
